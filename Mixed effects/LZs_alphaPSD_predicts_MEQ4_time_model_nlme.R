# =============================================================================
# OPTE: MEQ4 prediction models with LZs, alpha PSD, and time.
#
# This script mirrors the structure of the original LZc_predicts_MEQ4.R script:
#   Model 1: simple predictor -> MEQ4 association
#   Model 2: add Epoch as a time covariate
#   Model 3: test whether the predictor -> MEQ4 association varies by Epoch
#   Model comparisons: likelihood ratio tests using ML fits
#
# The new addition is alpha PSD:
#   - LZs-only models reproduce the original logic with the V7 LZs output.
#   - Alpha-PSD-only models ask whether alpha power predicts MEQ4.
#   - Combined models ask whether LZs and alpha PSD explain independent MEQ4
#     variance after accounting for time.
#
# Inputs are generated by alpha_PSD_LZs_MEQ_models_nlme.R:
#   outputs/PSD_band_LZs_mixed_models/alpha_psd_lzs_meq_epoch_avg.csv
#
# Notes:
#   - MEQ mapping follows the reference analysis script:
#       T4 -> Epoch1, T6 -> Epoch2, T8 -> Epoch3, T9 -> Epoch4
#   - MEQ4 has no eye condition, so alpha PSD and LZs are averaged across EC/EO.
#   - z_Mean_LZs and z_Log10Power include the baseline epoch in the z-scoring
#     reference distribution upstream, matching the spirit of the reference analysis script.
# =============================================================================

