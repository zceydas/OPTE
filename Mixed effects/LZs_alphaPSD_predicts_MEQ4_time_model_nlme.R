eta2p_from_anova <- function(aov_table) {
  out <- as.data.frame(aov_table)
  out$Term <- rownames(out)
  rownames(out) <- NULL
  if (all(c("F-value", "numDF", "denDF") %in% names(out))) {
    out$partial_eta2 <- with(out, (`F-value` * numDF) / (`F-value` * numDF + denDF))
  } else {
    out$partial_eta2 <- NA_real_
  }
  out
}

fit_lme <- function(data, formula_text, method = "REML") {
  lme(
    fixed = as.formula(formula_text),
    random = ~1 | Participant,
    data = data,
    method = method,
    na.action = na.omit,
    control = lmeControl(opt = "optim", maxIter = 200, msMaxIter = 200)
  )
}

tidy_fixed <- function(model, model_set, model_id, window_sec, formula_text, n, n_participants) {
  coefs <- as.data.frame(summary(model)$tTable)
  coefs$Term <- rownames(coefs)
  rownames(coefs) <- NULL
  data.frame(
    ModelSet = model_set,
    ModelID = model_id,
    WindowSec = window_sec,
    Formula = formula_text,
    Term = coefs$Term,
    Estimate = coefs$Value,
    Std_Error = coefs$Std.Error,
    DF = coefs$DF,
    t_value = coefs$`t-value`,
    p_value = coefs$`p-value`,
    Sigma = sigma(model),
    Cohens_d = coefs$Value / sigma(model),
    N = n,
    N_Participants = n_participants,
    stringsAsFactors = FALSE
  )
}

tidy_anova <- function(model, model_set, model_id, window_sec, formula_text, n, n_participants) {
  aov <- eta2p_from_anova(anova(model))
  data.frame(
    ModelSet = model_set,
    ModelID = model_id,
    WindowSec = window_sec,
    Formula = formula_text,
    Term = aov$Term,
    numDF = aov$numDF,
    denDF = aov$denDF,
    F_value = aov$`F-value`,
    p_value = aov$`p-value`,
    partial_eta2 = aov$partial_eta2,
    N = n,
    N_Participants = n_participants,
    stringsAsFactors = FALSE
  )
}

lrt_table <- function(models, labels, model_set, window_sec) {
  cmp <- anova(models[[1]], models[[2]], models[[3]])
  out <- as.data.frame(cmp)
  out$ModelID <- labels
  out$ModelSet <- model_set
  out$WindowSec <- window_sec
  out$Formula <- vapply(models, function(m) paste(deparse(formula(m)), collapse = " "), character(1))
  out <- out[, c("ModelSet", "WindowSec", "ModelID", "Formula", setdiff(names(out), c("ModelSet", "WindowSec", "ModelID", "Formula")))]
  rownames(out) <- NULL
  out
}

two_model_lrt <- function(reduced, full, reduced_label, full_label, model_set, window_sec) {
  cmp <- anova(reduced, full)
  out <- as.data.frame(cmp)
  out$ModelID <- c(reduced_label, full_label)
  out$ModelSet <- model_set
  out$WindowSec <- window_sec
  out$Formula <- c(
    paste(deparse(formula(reduced)), collapse = " "),
    paste(deparse(formula(full)), collapse = " ")
  )
  out <- out[, c("ModelSet", "WindowSec", "ModelID", "Formula", setdiff(names(out), c("ModelSet", "WindowSec", "ModelID", "Formula")))]
  rownames(out) <- NULL
  out
}

model_specs <- list(
  LZs_only = c(
    M1_simple = "MEQ4 ~ z_Mean_LZs",
    M2_time_controlled = "MEQ4 ~ z_Mean_LZs + Epoch",
    M3_time_interaction = "MEQ4 ~ z_Mean_LZs * Epoch"
  ),
  AlphaPSD_only = c(
    M1_simple = "MEQ4 ~ z_Log10Power",
    M2_time_controlled = "MEQ4 ~ z_Log10Power + Epoch",
    M3_time_interaction = "MEQ4 ~ z_Log10Power * Epoch"
  ),
  LZs_plus_AlphaPSD = c(
    M1_simple = "MEQ4 ~ z_Mean_LZs + z_Log10Power",
    M2_time_controlled = "MEQ4 ~ z_Mean_LZs + z_Log10Power + Epoch",
    M3_time_interaction = "MEQ4 ~ (z_Mean_LZs + z_Log10Power) * Epoch"
  )
)

fixed_rows <- list()
anova_rows <- list()
lrt_rows <- list()
increment_rows <- list()

for (window_sec in sort(unique(df$WindowSec))) {
  sub <- df[df$WindowSec == window_sec, ]
  sub <- droplevels(sub)
  n <- nrow(sub)
  n_participants <- length(unique(sub$Participant))

  cat("\n══════════════════════════════════════════════════════\n")
  cat(" Window ", window_sec, "s: N obs = ", n, " across ", n_participants, " participants\n", sep = "")
  cat("══════════════════════════════════════════════════════\n")

  for (model_set in names(model_specs)) {
    formulas <- model_specs[[model_set]]

    cat("\n", model_set, "\n", sep = "")
    reml_models <- lapply(formulas, function(f) fit_lme(sub, f, method = "REML"))
    ml_models <- lapply(formulas, function(f) fit_lme(sub, f, method = "ML"))

    for (model_id in names(reml_models)) {
      fixed_rows[[length(fixed_rows) + 1]] <- tidy_fixed(
        reml_models[[model_id]], model_set, model_id, window_sec,
        formulas[[model_id]], n, n_participants
      )
      anova_rows[[length(anova_rows) + 1]] <- tidy_anova(
        reml_models[[model_id]], model_set, model_id, window_sec,
        formulas[[model_id]], n, n_participants
      )

      cat("\n", model_id, ": ", formulas[[model_id]], "\n", sep = "")
      print(summary(reml_models[[model_id]])$tTable)
      cat("ANOVA:\n")
      print(anova(reml_models[[model_id]]))
    }

    cat("\nLikelihood ratio model comparison for ", model_set, ":\n", sep = "")
    cmp <- anova(ml_models[[1]], ml_models[[2]], ml_models[[3]])
    print(cmp)
    lrt_rows[[length(lrt_rows) + 1]] <- lrt_table(
      ml_models, names(ml_models), model_set, window_sec
    )
  }

  # Does alpha PSD add to LZs after time? Does LZs add to alpha PSD after time?
  lzs_time <- fit_lme(sub, "MEQ4 ~ z_Mean_LZs + Epoch", method = "ML")
  psd_time <- fit_lme(sub, "MEQ4 ~ z_Log10Power + Epoch", method = "ML")
  both_time <- fit_lme(sub, "MEQ4 ~ z_Mean_LZs + z_Log10Power + Epoch", method = "ML")

  increment_rows[[length(increment_rows) + 1]] <- two_model_lrt(
    lzs_time, both_time,
    "LZs + Epoch",
    "LZs + alpha PSD + Epoch",
    "Does alpha PSD add above LZs + time?",
    window_sec
  )
  increment_rows[[length(increment_rows) + 1]] <- two_model_lrt(
    psd_time, both_time,
    "alpha PSD + Epoch",
    "LZs + alpha PSD + Epoch",
    "Does LZs add above alpha PSD + time?",
    window_sec
  )
}

fixed_results <- do.call(rbind, fixed_rows)
anova_results <- do.call(rbind, anova_rows)
lrt_results <- do.call(rbind, lrt_rows)
increment_results <- do.call(rbind, increment_rows)

write.csv(
